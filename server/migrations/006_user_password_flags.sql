-- SIF Studio / 联锁工坊 — v006 迁移：账号生命周期（阶段 F2）
--
-- 背景：owner 通过成员管理（或运维通过 CLI 破窗命令）为他人重置密码后，
--       新密码是管理员设定的临时密码，不应长期使用。置位后用户下次进入
--       系统会被强制改密（见 /api/auth/me 的 mustChangePassword 字段与
--       前端路由守卫）；自助改密成功即清零。
--
-- 存量用户默认 0（无需强制），与历史行为完全兼容。
-- ===========================================================================

ALTER TABLE user ADD COLUMN must_change_password INTEGER NOT NULL DEFAULT 0;
